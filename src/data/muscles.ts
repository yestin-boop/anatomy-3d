const MESH_LAYER = new Map<string, MuscleLayer>()
for (const m of MUSCLES) {
  for (const name of m.meshNames) MESH_LAYER.set(name, m.layer)
}

export function muscleLayerForMesh(meshName: string): MuscleLayer | null {
  return MESH_LAYER.get(meshName) ?? null
}

export function muscleVisibleAtLayer(meshName: string, filter: MuscleLayerFilter): boolean {
  if (filter === 'all') return true
  const layer = muscleLayerForMesh(meshName)
  if (!layer) return true
  if (filter === 'mid') return layer !== 'superficial'
  return layer === 'deep'
}

export function normalizeMuscleAnswer(raw: string): string {
  return raw
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9\s]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

export function muscleAnswersMatch(typed: string, m: Muscle): boolean {
  const n = normalizeMuscleAnswer(typed)
  if (!n) return false
  const compact = n.replace(/\s+/g, '')
  return m.aliases.some((a) => {
    const na = normalizeMuscleAnswer(a)
    return na === n || na.replace(/\s+/g, '') === compact
  })
}

export function filterMuscles(regions: Iterable<MuscleRegion>): Muscle[] {
  const set = new Set(regions)
  return MUSCLES.filter((m) => set.has(m.region))
}

